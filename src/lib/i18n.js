const DICTS = { en, fr, it };

export function makeT(lang) {
  const d = DICTS[lang] || en;
  return (key, vars) => {
    let s = d[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}

export function localeFor(lang) {
  return (LANGS.find((l) => l.id === lang) || LANGS[0]).locale;
}

export function guessLang() {
  const n = (typeof navigator !== 'undefined' && navigator.language) || 'en';
  const code = n.slice(0, 2).toLowerCase();
  return DICTS[code] ? code : 'en';
}

// "3 minutes ago" style relative time.
export function relTime(ts, lang) {
  const rtf = new Intl.RelativeTimeFormat(localeFor(lang), { numeric: 'auto' });
  const s = Math.round((ts - Date.now()) / 1000);
  const abs = Math.abs(s);
  if (abs < 60) return rtf.format(s, 'second');
  if (abs < 3600) return rtf.format(Math.round(s / 60), 'minute');
  if (abs < 86400) return rtf.format(Math.round(s / 3600), 'hour');
  return rtf.format(Math.round(s / 86400), 'day');
}
